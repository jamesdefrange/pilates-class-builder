#!/usr/bin/env node
// Copies every JSON file in /data into data/data.js so the app works when index.html
// is opened straight from disk (browsers block reading JSON files that way).
// Run after editing any file in /data:  node scripts/build-data.js
const fs = require('fs');
const path = require('path');

const dataDir = path.join(__dirname, '..', 'data');
const files = ['levels', 'client-groups', 'class-types', 'equipment', 'exercises', 'peak-poses', 'abbreviations'];

const bundle = {};
for (const name of files) {
  const file = path.join(dataDir, name + '.json');
  try {
    bundle[name] = JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (err) {
    console.error('Could not read ' + name + '.json: ' + err.message);
    process.exit(1);
  }
}

const out = '// Generated by scripts/build-data.js. Do not edit by hand: edit the JSON files and run the script again.\n' +
  'window.PCB_DATA = ' + JSON.stringify(bundle) + ';\n';
fs.writeFileSync(path.join(dataDir, 'data.js'), out);
console.log('data/data.js written (' + bundle.exercises.exercises.length + ' exercises, ' + bundle['peak-poses'].peaks.length + ' peak poses)');
